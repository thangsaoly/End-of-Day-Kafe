package com.kafe.android.auth

import android.annotation.SuppressLint
import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential

/** The user closed the Google account picker; not an error to show. */
class GoogleSignInCancelled : Exception()

/**
 * Shows the "Sign in with Google" sheet and returns a Google ID token for Firebase.
 * [activityContext] must be an Activity context.
 */
suspend fun requestGoogleIdToken(activityContext: Context): String {
    val webClientId = webClientId(activityContext)
        ?: throw Exception("Google sign-in isn't set up yet: enable it in the Firebase console and update google-services.json.")

    val request = GetCredentialRequest.Builder()
        .addCredentialOption(GetSignInWithGoogleOption.Builder(webClientId).build())
        .build()

    val credential = try {
        CredentialManager.create(activityContext).getCredential(activityContext, request).credential
    } catch (e: GetCredentialCancellationException) {
        throw GoogleSignInCancelled()
    } catch (e: NoCredentialException) {
        throw Exception("No Google account found on this device.")
    } catch (e: GetCredentialException) {
        throw Exception("Google sign-in failed: ${e.message}")
    }

    if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
        return GoogleIdTokenCredential.createFrom(credential.data).idToken
    }
    throw Exception("Google sign-in returned an unexpected credential.")
}

// Generated by the google-services plugin only once Google sign-in is enabled for the
// project. Looked up by name so the app still builds before that.
@SuppressLint("DiscouragedApi")
private fun webClientId(context: Context): String? {
    val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
    return if (id != 0) context.getString(id) else null
}
